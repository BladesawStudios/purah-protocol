"""Writes probe/src/book_stubs.hpp: one tiny assembly entry per book row (see probe/src/entry.hpp).

    python tools/make_stubs.py probe/src/book_data.hpp probe/src/book_stubs.hpp

Each stub loads its row number into w16 and branches to purah_common. The row count is read from book_data.hpp, so the two always agree.
"""
import re
import sys

source, target = sys.argv[1:3]
count = int(re.search(r"kCount = (\d+);", open(source, encoding="utf-8").read()).group(1))

out = ["// GENERATED by tools/make_stubs.py. Do not edit.", "#pragma once", "#include \"book_data.hpp\"", "", 'asm(R"(', "    .text"]
for i in range(count):
    out += ["    .balign 4", "    .global purah_stub_%d" % i, "purah_stub_%d:" % i, "    mov   w16, #%d" % i, "    b     purah_common"]
out += [')");', "", 'extern "C" {']
out += ["void purah_stub_%d();" % i for i in range(count)]
out += ["}", "", "namespace purah::book {", "", "using StubFn = void (*)();", "", "constexpr StubFn kStubs[kCount] = {"]
out += ["    &purah_stub_%d," % i for i in range(count)]
out += ["};", "", "}  // namespace purah::book", ""]
open(target, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("%d stubs" % count)
